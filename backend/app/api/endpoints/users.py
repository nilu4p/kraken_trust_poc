"""User administration (admin) and assignable analysts (analyst+)."""

from __future__ import annotations

from typing import Any, Dict, Optional

from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel, Field

from app.api.deps import admin, analyst
from app.core import identity

router = APIRouter(prefix="/users", tags=["users"])


class UserCreate(BaseModel):
    username: str = Field(..., min_length=2, max_length=64)
    display_name: str = Field("", max_length=120)
    role: str
    password: Optional[str] = Field(None, max_length=256)


class UserUpdate(BaseModel):
    display_name: Optional[str] = Field(None, max_length=120)
    role: Optional[str] = None
    disabled: Optional[bool] = None


@router.get("")
def list_users(_user: Dict[str, Any] = Depends(admin)) -> Dict[str, Any]:
    return {"users": identity.list_users(), "roles": identity.ROLE_LABELS}


@router.get("/assignable")
def assignable(_user: Dict[str, Any] = Depends(analyst)) -> Dict[str, Any]:
    users = [
        {"id": u["id"], "username": u["username"], "display_name": u["display_name"], "role": u["role"]}
        for u in identity.list_users()
        if not u["disabled"] and identity.has_role(u, "analyst")
    ]
    return {"users": users}


@router.post("")
def create(body: UserCreate, user: Dict[str, Any] = Depends(admin)) -> Dict[str, Any]:
    from app.core.passwords import generate_password

    temporary = body.password or generate_password()
    try:
        created = identity.create_user(
            body.username, temporary, body.role, display_name=body.display_name, actor=user["username"]
        )
    except ValueError as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc
    if created["role"] == "admin":
        from app.soc import notify

        notify.notify_security(
            f"Nouvel administrateur créé depuis l'interface : {created['username']}",
            details={"Compte": created["username"], "Créé par": user["username"]},
        )
    # The temporary password is returned once, only when generated by the server.
    return {"user": created, "temporary_password": None if body.password else temporary}


@router.patch("/{user_id}")
def update(user_id: int, body: UserUpdate, user: Dict[str, Any] = Depends(admin)) -> Dict[str, Any]:
    try:
        before = identity.get_user(user_id)
        updated = identity.update_user(
            user_id, role=body.role, display_name=body.display_name, disabled=body.disabled, actor=user
        )
        if body.role == "admin" and before is not None and before["role"] != "admin":
            from app.soc import notify

            notify.notify_security(
                f"Élévation au rôle administrateur : {updated['username']}",
                details={"Compte": updated["username"], "Par": user["username"]},
            )
    except LookupError as exc:
        raise HTTPException(status_code=404, detail=str(exc)) from exc
    except ValueError as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc
    return {"user": updated}


@router.post("/{user_id}/reset-password")
def reset(user_id: int, user: Dict[str, Any] = Depends(admin)) -> Dict[str, Any]:
    try:
        temporary = identity.reset_password(user_id, actor=user)
    except LookupError as exc:
        raise HTTPException(status_code=404, detail=str(exc)) from exc
    return {"temporary_password": temporary}
